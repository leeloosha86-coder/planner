const CYCLE_DAYS = 366;
const ANCHOR_UTC = Date.UTC(2026, 10, 16);

export function tipForDate(date: Date): string | null {
  const today = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const elapsed = Math.round((today - ANCHOR_UTC) / 86400000);
  const index = ((elapsed % CYCLE_DAYS) + CYCLE_DAYS) % CYCLE_DAYS;
  return TIPS[index] ?? null;
}
